import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createEmptyDocumentation, getAppVersion } from '../lib/gobd-template';
import { hashPassword } from '../lib/password';
import { prisma } from '../lib/prisma';
import { e2eDatabasePath } from '../scripts/e2e-fixture.mjs';

test('prints every original documentation section while keeping screen sections initially collapsed', async ({ page }, testInfo) => {
  expect(process.env.DATABASE_URL).toBe(`file:${e2eDatabasePath()}`);
  const password = 'SyntheticDocumentationPrint123!';
  const user = await prisma.user.create({ data: {
    email: `documentation-print-${randomUUID()}@example.test`,
    name: 'Synthetic documentation print',
    password: await hashPassword(password),
  } });
  const original = createEmptyDocumentation();
  const markers = original.sections.map(section => `SYNTHETIC ORIGINAL ${section.id} ${randomUUID()}`);
  original.sections = original.sections.map((section, index) => ({
    ...section,
    content: `${section.content}\n\n${markers[index]}`,
  }));
  const serialized = JSON.stringify(original);
  const document = await prisma.documentation.create({ data: {
    userId: user.id, version: getAppVersion(), title: 'Synthetic original documentation', content: serialized,
  } });

  await page.goto('/login');
  await page.getByLabel('E-Mail').fill(user.email);
  await page.getByLabel('Passwort', { exact: true }).fill(password);
  await page.getByRole('main').getByRole('button', { name: 'Anmelden', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard/);
  await page.goto('/settings/documentation');
  await expect(page.getByRole('heading', { name: 'Dokumentation', exact: true })).toBeVisible();

  for (const [index, section] of original.sections.entries()) {
    const region = page.locator(`#gobd-${section.id}`);
    const content = region.locator('[data-slot="collapsible-content"]');
    const trigger = region.locator('[data-slot="collapsible-trigger"]');
    await expect(trigger).toHaveAttribute('aria-expanded', 'false');
    await expect(content).toHaveCount(1);
    await expect(content).toBeHidden();
    await expect(content).toContainText(markers[index]);
    if (!section.isAutoGenerated) await expect(region.getByRole('textbox', { includeHidden: true })).toHaveValue(section.content);
    await trigger.press('Enter');
    await expect(content).toBeVisible();
    await trigger.press('Enter');
    await expect(content).toBeHidden();
  }

  await page.emulateMedia({ media: 'print' });
  for (const [index, section] of original.sections.entries()) {
    const region = page.locator(`#gobd-${section.id}`);
    const content = region.locator('[data-slot="collapsible-content"]');
    await expect(content).toBeVisible();
    await expect(region.getByText(markers[index], { exact: true })).toBeVisible();
    if (!section.isAutoGenerated) await expect(region.getByRole('textbox', { includeHidden: true })).toBeHidden();
    // Compare the entire rendered source, ignoring Markdown punctuation and layout spacing.
    const originalCharacters = section.content.replace(/[^\p{L}\p{N}]/gu, '');
    expect((await content.innerText()).replace(/[^\p{L}\p{N}]/gu, '')).toBe(originalCharacters);
  }
  await page.screenshot({ path: testInfo.outputPath('documentation-all-original-sections-print.png'), fullPage: true });
  await page.emulateMedia({ media: 'screen' });
  for (const section of original.sections) await expect(page.locator(`#gobd-${section.id} [data-slot="collapsible-content"]`)).toBeHidden();
  expect((await prisma.documentation.findUniqueOrThrow({ where: { id: document.id } })).content).toBe(serialized);
});
