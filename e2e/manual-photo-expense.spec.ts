import { expect, test } from '@playwright/test';
import { createHash, randomUUID } from 'node:crypto';
import sharp from 'sharp';
import JSZip from 'jszip';
import { hashPassword } from '../lib/password';
import { prisma } from '../lib/prisma';
import { e2eDatabasePath } from '../scripts/e2e-fixture.mjs';

test('saved mobile photo needs explicit source/payment confirmation and safely replays one original-backed Expense', async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  expect(process.env.DATABASE_URL).toBe(`file:${e2eDatabasePath()}`);
  const password = 'SyntheticManualPhoto123!';
  const email = `manual-photo-${randomUUID()}@example.test`;
  const user = await prisma.user.create({ data: { email, name: 'Synthetic manual photo approval', password: await hashPassword(password), role: 'USER' } });
  const photo = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="780" height="1120"><rect width="780" height="1120" fill="#faf6ed"/><g fill="#20372b" font-family="sans-serif"><text x="60" y="110" font-size="38">SYNTHETISCHE RECHNUNG</text><text x="60" y="190" font-size="28">Foto Lieferant · PHOTO-PAID-17</text><text x="60" y="260" font-size="28">31.12.2025 · EUR</text><text x="60" y="360" font-size="48">0,29 EUR</text><text x="60" y="450" font-size="24">Kein echter Geschäftsvorfall.</text></g></svg>')).png().toBuffer();
  try {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ colorScheme: 'light' });
    await page.goto('/login');
    await page.getByLabel('E-Mail').fill(email);
    await page.getByLabel('Passwort', { exact: true }).fill(password);
    await page.getByRole('main').getByRole('button', { name: 'Anmelden', exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard/);
    await page.goto('/purchases');
    await page.getByLabel('Foto, PDF- oder XML-Original auswählen', { exact: true }).setInputFiles({ name: 'synthetic-paid-photo.png', mimeType: 'image/png', buffer: photo });
    await page.getByRole('button', { name: 'Original hochladen', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog.getByRole('img', { name: /Unverändertes Foto-Original/ })).toBeVisible();
    await dialog.getByLabel('Lieferant', { exact: true }).fill('Foto Lieferant');
    await dialog.getByLabel('Rechnungsnummer', { exact: true }).fill('PHOTO-PAID-17');
    await dialog.getByLabel('Rechnungsdatum', { exact: true }).fill('2025-12-31');
    await dialog.getByLabel('Zahlungsdatum', { exact: true }).fill('2026-01-01');
    await dialog.getByLabel('Bruttobetrag (EUR)', { exact: true }).fill('0,29');
    await expect(dialog.getByRole('button', { name: 'Als Ausgabe erfassen', exact: true })).toBeDisabled();
    expect(await prisma.expense.count({ where: { userId: user.id } })).toBe(0);
    await dialog.getByRole('button', { name: 'Prüfentwurf speichern', exact: true }).click();
    await expect(dialog.getByText('Prüfentwurf gespeichert · nicht gebucht', { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Kontakt auswählen / anlegen', exact: true }).click();
    await dialog.getByRole('button', { name: 'Kontakt neu anlegen', exact: true }).click();
    await dialog.getByLabel('Name *', { exact: true }).fill('Foto Prüfkontakt');
    await dialog.getByRole('button', { name: 'Kontakt speichern', exact: true }).click();
    await dialog.getByRole('button', { name: 'Für diesen Beleg auswählen', exact: true }).click();
    await expect(dialog.getByRole('button', { name: 'Als Ausgabe erfassen', exact: true })).toBeEnabled();
    await dialog.getByRole('button', { name: 'Als Ausgabe erfassen', exact: true }).click();
    await expect(dialog.getByText('Angaben aus dem gespeicherten Prüfentwurf am Foto prüfen. Änderungen dort speichern.', { exact: true })).toBeVisible();
    await expect(dialog.getByLabel('Tatsächliches Zahlungsdatum', { exact: true })).toHaveValue('2026-01-01');
    await expect(dialog.getByLabel('Tatsächliches Zahlungsdatum', { exact: true })).toHaveAttribute('readonly', '');
    await dialog.getByLabel('Empfänger / Käufer laut Foto-Original', { exact: true }).fill('Mein synthetischer Betrieb');
    await dialog.getByLabel('Beschreibung / betrieblicher Zweck', { exact: true }).fill('Synthetischer Bürobedarf für den Betrieb');
    await dialog.getByLabel('Kategorie', { exact: true }).fill('Büromaterial');
    await dialog.getByLabel('Steuerlich berücksichtigen?', { exact: true }).selectOption('no');
    await dialog.getByLabel('Betrieblicher / abziehbarer Anteil in %', { exact: true }).fill('75');
    await dialog.getByRole('button', { name: 'Weiter zur Bestätigung', exact: true }).click();
    await expect(dialog.getByText('Manuelle Foto-Originalprüfung · keine Extraktion', { exact: true })).toBeVisible();
    const final = dialog.getByRole('button', { name: 'Zahlung bestätigen und Ausgabe erfassen', exact: true });
    await expect(final).toBeDisabled();
    for (const id of ['purchase-photo-owned', 'purchase-photo-exact', 'purchase-photo-ordinary', 'purchase-reviewed', 'purchase-buyer']) await dialog.locator(`#${id}`).check();
    await expect(final).toBeDisabled();
    expect(await prisma.expense.count({ where: { userId: user.id } })).toBe(0);
    await dialog.locator('#purchase-paid').check();
    await expect(final).toBeEnabled();
    await dialog.screenshot({ path: testInfo.outputPath('manual-photo-confirmation-mobile.png'), animations: 'disabled' });
    let submitted: Record<string, unknown> | null = null;
    // Server commits, then transport fails: repeat must use the identical idempotency request.
    await page.route('**/approve-expense', async route => {
      submitted = route.request().postDataJSON();
      const response = await route.fetch(); expect(response.status()).toBe(200);
      await route.abort('failed');
    }, { times: 1 });
    await final.click();
    await expect(dialog.getByRole('alert')).toContainText('Antwort ist unklar');
    expect(await prisma.expense.count({ where: { userId: user.id } })).toBe(1);
    const retried = page.waitForRequest(request => request.url().endsWith('/approve-expense'));
    await dialog.getByRole('button', { name: 'Dieselbe Anfrage sicher wiederholen', exact: true }).click();
    expect((await retried).postDataJSON()).toEqual(submitted);
    await expect(dialog.getByText(/Ausgabe #\d+ gespeichert/)).toBeVisible();
    const source = await prisma.purchaseDocument.findFirstOrThrow({ where: { userId: user.id } });
    expect(source).toMatchObject({ reviewStatus: 'BOOKED', reviewedSourceSnapshot: { provenance: 'MANUAL_PHOTO_REVIEW', paymentDate: '2026-01-01', grossAmount: '0.29' } });
    await dialog.getByRole('link', { name: 'Gespeicherte Ausgabe ansehen', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`/expenses/${source.expenseId}$`));
    await expect(page.getByText(/Manuelle Foto-Originalprüfung bestätigt/)).toBeVisible();
    await page.reload();
    await expect(page.getByText(/Manuelle Foto-Originalprüfung bestätigt/)).toBeVisible();
    expect(await prisma.expense.count({ where: { userId: user.id } })).toBe(1);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.getByRole('main').screenshot({ path: testInfo.outputPath('manual-photo-expense-desktop.png'), animations: 'disabled' });
    const forbidden = await page.request.put('/api/expenses', { data: { id: source.expenseId, description: 'Not allowed', amount: 1 } }); expect(forbidden.status()).toBe(409);
    const preview = await page.request.get('/api/accountant-export?year=2026&preview=1'); expect(preview.status()).toBe(200);
    const manifest = (await preview.json()).manifest; expect(manifest.counts.expenses).toBe(1);
    const pack = await page.request.get(`/api/accountant-export?year=2026&expectedFingerprint=${manifest.sourceFingerprint}`); expect(pack.status()).toBe(200);
    const zip = await JSZip.loadAsync(await pack.body());
    const records = JSON.parse(await zip.file('records.json')!.async('string'));
    expect(records.expenses).toHaveLength(1); expect(records.expenses[0]).toMatchObject({ amountCents: '29', sourceReviewProvenance: 'MANUAL_PHOTO_REVIEW' });
    expect(createHash('sha256').update(await zip.file(`originals/expense-${source.expenseId}.png`)!.async('nodebuffer')).digest('hex')).toBe(createHash('sha256').update(photo).digest('hex'));
    const wrongYear = await page.request.get('/api/accountant-export?year=2025&preview=1'); expect(wrongYear.status()).toBe(200); expect((await wrongYear.json()).manifest.counts.expenses).toBe(0);
    expect(await prisma.income.count({ where: { userId: user.id } })).toBe(0); expect(await prisma.cashTransaction.count({ where: { userId: user.id } })).toBe(0);
  } finally { await prisma.$disconnect(); }
});
